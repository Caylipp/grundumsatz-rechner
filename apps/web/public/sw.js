// Minimaler Service Worker: macht den Rechner offline nutzbar (App-Modus).
// Alle Pfade sind relativ zum Speicherort dieser Datei, damit die Seite auch unter einem Unterpfad läuft.
const CACHE = 'grundumsatz-v2';
const CORE = ['./', './methodik/', './en/', './es/', './vi/', './manifest.webmanifest', './icon.svg'];
const ROOT = new URL('./', self.location).href;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(CORE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // Seiten: erst Netz, dann Cache
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        })
        .catch(() => caches.match(req).then((r) => r || caches.match(ROOT))),
    );
  } else {
    // Assets (gehashte Dateinamen): erst Cache, dann Netz
    event.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(req, copy));
            }
            return res;
          }),
      ),
    );
  }
});
